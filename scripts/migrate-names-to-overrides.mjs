// Build a unified names lookup: id → { fr, en, es, de }
const allNames = new Map();

function setName(id, lang, val) {
  if (!val) return;
  if (!allNames.has(id)) allNames.set(id, {});
  allNames.get(id)[lang] = val;
}

for (const [id, name] of Object.entries(FRENCH_NAMES)) setName(id, 'fr', name);
for (const [id, name] of Object.entries(ENGLISH_NAMES)) setName(id, 'en', name);
for (const [id, name] of Object.entries(SPANISH_NAMES)) setName(id, 'es', name);
for (const [id, name] of Object.entries(GERMAN_NAMES)) setName(id, 'de', name);
for (const [id, name] of Object.entries(SH2_FRENCH_NAMES)) setName(id, 'fr', name);
for (const [id, name] of Object.entries(SH2_ENGLISH_NAMES)) setName(id, 'en', name);
for (const [id, name] of Object.entries(SH2_SPANISH_NAMES)) setName(id, 'es', name);
for (const [id, name] of Object.entries(SH2_GERMAN_NAMES)) setName(id, 'de', name);

// Load overrides file
const overrides = JSON.parse(readFileSync(OVERRIDES_PATH, 'utf8'));

let updated = 0;
let added = 0;

for (const entry of overrides) {
  // Collect all potential IDs for this entry (entry.id + entry.catalogs)
  const ids = new Set([entry.id]);
  if (Array.isArray(entry.catalogs)) {
    for (const cat of entry.catalogs) ids.add(cat);
  }

  // Find a matching names block
  const merged = {};
  for (const id of ids) {
    const names = allNames.get(id);
    if (names) {
      if (names.fr && !merged.fr) merged.fr = names.fr;
      if (names.en && !merged.en) merged.en = names.en;
      if (names.es && !merged.es) merged.es = names.es;
      if (names.de && !merged.de) merged.de = names.de;
    }
  }

  if (Object.keys(merged).length === 0) continue;

  if (!entry.names) {
    entry.names = merged;
    added++;
  } else {
    // Merge without overwriting existing values
    let changed = false;
    for (const lang of ['fr', 'en', 'es', 'de']) {
      if (merged[lang] && !entry.names[lang]) {
        entry.names[lang] = merged[lang];
        changed = true;
      }
    }
    if (changed) updated++;
  }
}

// Also add entries for DSOs that have names but no override entry yet
// (rare case: a named DSO not in the overrides file at all)
const existingIds = new Set(overrides.map(e => e.id));
for (const [id, names] of allNames) {
  if (!existingIds.has(id)) {
    overrides.push({ id, names, catalogs: [id] });
    added++;
    console.log(`  New entry for ${id}`);
  }
}

writeFileSync(OVERRIDES_PATH, JSON.stringify(overrides, null, 2) + '\n', 'utf8');
console.log(`Done. Added names to ${added} new, merged into ${updated} existing entries.`);
console.log(`Total entries: ${overrides.length}`);
