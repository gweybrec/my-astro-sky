// ─── Precession J2000 → B1875 (Lieske et al. 1977) ─────────────────────────
function j2000ToB1875(raDeg, decDeg) {
  const DEG = Math.PI / 180;
  // T0 = 0 (J2000.0), t = -1.25 centuries (J2000 → B1875)
  const t = -1.25;
  const as2rad = DEG / 3600;

  const zetaA  = ((2306.2181) * t + 0.30188 * t * t + 0.017998 * t * t * t) * as2rad;
  const thetaA = ((2004.3109) * t - 0.42665 * t * t - 0.041775 * t * t * t) * as2rad;
  const zA     = ((2306.2181) * t + 1.09468 * t * t + 0.018203 * t * t * t) * as2rad;

  const ra  = raDeg  * DEG;
  const dec = decDeg * DEG;

  const A = Math.cos(dec) * Math.sin(ra + zetaA);
  const B = Math.cos(thetaA) * Math.cos(dec) * Math.cos(ra + zetaA) - Math.sin(thetaA) * Math.sin(dec);
  const C = Math.sin(thetaA) * Math.cos(dec) * Math.cos(ra + zetaA) + Math.cos(thetaA) * Math.sin(dec);

  return {
    ra:  (((Math.atan2(A, B) + zA) / DEG) % 360 + 360) % 360,
    dec: Math.asin(Math.max(-1, Math.min(1, C))) / DEG,
  };
}

// ─── Fetch Roman (1987) boundary table from CDS ─────────────────────────────
// Format: fixed-width cols 1-4 RA (hours), 5-10 Dec (deg), 11-13 abbr (B1875)
// Format: 4 space-separated columns: ra_lower ra_upper dec_lower constellation (B1875)
async function fetchBoundaries() {
  const url = 'https://cdsarc.cds.unistra.fr/ftp/VI/42/data.dat';
  console.log('Fetching boundary data from CDS...');
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${url}`);
  const text = await res.text();
  const table = [];
  for (const line of text.split('\n')) {
    const parts = line.trim().split(/\s+/);
    if (parts.length < 4) continue;
    const raLow   = parseFloat(parts[0]);
    const raUpper = parseFloat(parts[1]);
    const decLow  = parseFloat(parts[2]);
    const abbr    = parts[3];
    if (!isNaN(raLow) && !isNaN(raUpper) && !isNaN(decLow) && abbr) {
      table.push([raLow, raUpper, decLow, abbr]);
    }
  }
  if (table.length < 100) throw new Error(`Suspiciously short table: ${table.length} entries`);
  console.log(`Loaded ${table.length} boundary entries.`);
  return table;
}

