// ─── Lookup ─────────────────────────────────────────────────────────────────
function getConstellation(raDeg, decDeg) {
  const b1875 = j2000ToB1875(raDeg, decDeg);
  const raH = b1875.ra / 15.0;
  const dec = b1875.dec;

  for (const [raLow, raUpper, decLow, abbr] of BOUNDARIES) {
    if (dec >= decLow && raH >= raLow && raH < raUpper) {
      return abbr;
    }
  }
  return null;
}

// ─── Main (async: fetches boundary data, then patches dso.json) ─────────────
async function main() {
  // Fetch the authoritative Roman 1987 boundary table from CDS (overrides legacy fallback)
  try {
    BOUNDARIES = await fetchBoundaries();
  } catch (e) {
    console.warn('Warning: could not fetch CDS data, using fallback table:', e.message);
  }

  const raw = JSON.parse(readFileSync(DSO_PATH, 'utf8'));
  const fields = raw.fields;

  if (fields.includes('constellation')) {
    console.log('constellation field already present, re-computing values...');
  } else {
    fields.push('constellation');
    console.log('Added constellation field at index', fields.length - 1);
  }

  const idxConst = fields.indexOf('constellation');
  const idxRa    = fields.indexOf('ra');
  const idxDec   = fields.indexOf('dec');

  let assigned = 0;
  let failed   = 0;

  for (const row of raw.data) {
    const ra  = row[idxRa];
    const dec = row[idxDec];
    const c = getConstellation(ra, dec);
    if (row.length < idxConst + 1) row.push(c);
    else row[idxConst] = c;
    if (c) assigned++; else failed++;
  }

  writeFileSync(DSO_PATH, JSON.stringify(raw));
  console.log(`Done. Assigned: ${assigned}, Failed: ${failed} / Total: ${raw.data.length}`);

  // Sanity check on well-known objects
  const knownChecks = [
    { id: 'M31', expectedConst: 'And' },
    { id: 'M42', expectedConst: 'Ori' },
    { id: 'M51', expectedConst: 'CVn' },
    { id: 'M57', expectedConst: 'Lyr' },
  ];
  const idIdx = fields.indexOf('id');
  for (const { id, expectedConst } of knownChecks) {
    const row = raw.data.find(r => r[idIdx] === id);
    const actual = row ? row[idxConst] : '???';
    const ok = actual === expectedConst;
    console.log(`  ${id}: ${actual} ${ok ? '✓' : `✗ (expected ${expectedConst})`}`);
  }
}

main().catch(err => {
  console.error('Error:', err);
  process.exit(1);
});
